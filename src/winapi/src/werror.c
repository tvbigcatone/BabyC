DWORD posix_to_werror(int posixerr)
{
	DWORD error = ERROR_INVALID_FUNCTION;
	switch(posixerr) {
      case EACCES:       error = ERROR_INVALID_ACCESS;          break;
      case EBUSY:        error = ERROR_BUSY;                    break;
      case EEXIST:       error = ERROR_ALREADY_EXISTS;          break;
      case ERANGE:       error = ERROR_ARITHMETIC_OVERFLOW;     break;
      case EIO:          error = ERROR_GEN_FAILURE;             break;
      case ENODEV:       error = ERROR_FILE_INVALID;            break;
      case ENXIO:        error = ERROR_UNRECOGNIZED_MEDIA;      break;
      case ENOEXEC:      error = ERROR_BAD_EXE_FORMAT;          break;
      case EINVAL:       error = ERROR_INVALID_DATA;            break;
      case ENOENT:       error = ERROR_PATH_NOT_FOUND;          break;
      case EPIPE:        error = ERROR_NO_DATA;                 break;
      case ENAMETOOLONG: error = ERROR_BUFFER_OVERFLOW;         break;
      case ENOSYS:       error = ERROR_INVALID_FUNCTION;        break;
      case ENOTEMPTY:    error = ERROR_DIR_NOT_EMPTY;           break;
      case ENOSPC:       error = ERROR_DISK_FULL;               break;
      case ENOMEM:       error = ERROR_OUTOFMEMORY;             break;
      case EFAULT:       error = ERROR_NOACCESS;                break;
      case EBADF:        error = ERROR_INVALID_HANDLE;          break;
      case EPERM:        error = ERROR_INVALID_PASSWORD;        break;
      case EINTR:        error = ERROR_OPERATION_ABORTED;       break;
      case E2BIG:        error = ERROR_META_EXPANSION_TOO_LONG; break;
      case ESPIPE:       error = ERROR_SEEK_ON_DEVICE;          break;
      case EAGAIN:       error = ERROR_NOT_READY;               break;
      case EXDEV:        error = ERROR_NOT_SAME_DEVICE;         break;
      case ENFILE:       error = ERROR_SHARING_BUFFER_EXCEEDED; break;
      case EMLINK:       error = ERROR_TOO_MANY_LINKS;          break;
      case EMFILE:       error = ERROR_TOO_MANY_OPEN_FILES;     break;
      case ECHILD:       error = ERROR_WAIT_NO_CHILDREN;        break;
      case EROFS:        error = ERROR_WRITE_PROTECT;           break;
	}
	return error;
}

